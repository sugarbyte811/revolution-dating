function whatTheyArentSaying(p) {
  const hidden = ARCHETYPES[p.archetype.hidden];
  const shadow = SHADOWS[p.shadow.key];
  const out = [];

  out.push(
    `The presentation is ${ARCHETYPES[p.archetype.primary].name}. Underneath it, their responses repeatedly favoured ${hidden.name} when the scenario carried a real cost - which is the pattern that tends to show up only after several months.`
  );

  if (isPronounced(p, 'reassurance') && p.axes.closeness < 20) {
    out.push('They present as more self-sufficient than their answers indicate. The reassurance requirement is genuine and is likely to be under-reported in conversation.');
  }
  if (isPronounced(p, 'admiration')) {
    out.push('Regard is load-bearing for them and they are unlikely to say so, because saying so feels like vanity.');
  }
  if (isPronounced(p, 'beingSeen')) {
    out.push('Being accurately perceived matters more to them than being agreed with. Partners who are warm but incurious will not hold them.');
  }
  if (p.summary.giveReceiveSplit) {
    const g = p.summary.giveTop[0], r = p.summary.receiveTop[0];
    out.push(
      `They give love through ${LOVE_CHANNEL_LABEL[g.key].toLowerCase()} and need it returned as ${LOVE_CHANNEL_LABEL[r.key].toLowerCase()}. They almost certainly do not know this about themselves.`
    );
  }
  out.push(`Under strain they move toward ${shadow.name}. ${shadow.tell}`);

  return out;
}

function statedVsDemonstrated(p) {
  if (!p.stated.divergent) {
    return [
      'No significant divergence detected. What this client says they want and what their scenario choices indicate are broadly consistent, which makes them comparatively straightforward to brief and to match.'
    ];
  }
  const stated = ARCHETYPES[p.stated.top];
  const demo = ARCHETYPES[p.archetype.primary];
  return [
    `There appears to be a difference between their stated preference and the situations they selected. They described themselves in terms consistent with ${stated.name}.`,
    `Across the scenario questions, however, they consistently chose in a direction consistent with ${demo.name}.`,
    'Practically: expect the brief they give you in person to point one way and their actual responses to introductions to point another. Weight the behaviour, not the brief.',
    'Handle this carefully in conversation. It is usually not a lack of self-knowledge so much as a description of who they would like to be, which is worth respecting even while you match on the other thing.'
  ];
}

function chemistryNotes(p) {
  const creates = [];
  const sustains = [];
  const kills = [];

  const onset = p.summary.onsetTop[0];
  if (onset) creates.push(`Primarily ${ONSET_META[onset.key].phrase}.`);
  const onset2 = p.summary.onsetTop[1];
  if (onset2 && onset2.value > 15) creates.push(`Secondarily, ${ONSET_META[onset2.key].phrase}.`);
  if (p.axes.pursuit > 30) creates.push('Being actively and visibly pursued contributes materially to early attraction.');

  sustains.push(
    p.axes.novelty > 20
      ? 'Continued development in the partner. They need someone who is still becoming something.'
      : p.axes.novelty < -20
        ? 'Deepening familiarity. Being thoroughly known is what holds them rather than what bores them.'
        : 'A mixture of familiarity and movement, without a strong pull in either direction.'
  );
  if (p.axes.physical > 30) sustains.push('Ongoing physical charge. This does not become less important to them over time.');
  if (isPronounced(p, 'depth')) sustains.push('Genuine psychological access. Pleasantness alone will not hold them.');

  for (const k of p.summary.killTop) {
    kills.push(`${KILL_META[k.key].replace(/^./, (c) => c.toUpperCase())}.`);
  }
  if (p.axes.admiration > 40) kills.push('Loss of respect, which for this client is effectively terminal and usually silent.');
  if (p.axes.security > 40) kills.push('Uneven effort. Inconsistency costs them more than conflict does.');

  return { creates, sustains, kills };
}

function pursuitAndDistance(p) {
  const pursuit = [];
  const distance = [];

  pursuit.push(
    p.axes.pursuit > 30
      ? 'They expect to be pursued, genuinely and visibly, at least at the start. A partner who merely matches their energy will leave them uncertain, and they will read the uncertainty as a lack of interest rather than as a difference in style.'
      : p.axes.pursuit < -30
        ? 'They are comfortable initiating and do not require pursuit. Heavy courtship may read to them as performance.'
        : 'Pursuit expectations are moderate. Mutual initiation will work.'
  );
  if (p.axes.control > 30) {
    pursuit.push('Being planned for reads as care rather than presumption. Decisiveness is attractive to them; being consulted on every detail is not.');
  }
  if (p.axes.pace < -30) {
    pursuit.push('Do not apply time pressure. They move deliberately and respond badly to being asked for a verdict early.');
  }

  distance.push(
    p.axes.reassurance > 35
      ? 'Distance is experienced as information, and the information they infer is usually worse than the truth. Silence from a partner will be filled in, not waited out.'
      : p.axes.reassurance < -20
        ? 'They tolerate distance comfortably and may not notice a partner needing more contact than they do.'
        : 'Moderate response to distance. A short gap will not destabilise them.'
  );
  if (p.strategies.raw.interpret > 2) {
    distance.push('Their pattern under uncertainty is to interpret rather than ask. Expect a fully-formed private account of what a partner is thinking, built without checking.');
  }
  if (p.strategies.raw.exit > 2) {
    distance.push('Their pattern under strain is to quietly keep an alternative warm. Watch for reduced availability rather than for a stated problem.');
  }

  return { pursuit, distance };
}

function fightAndRepair(p) {
  const style = p.summary.conflictTop[0];
  const fights = [];
  const repairs = [];

  if (style) {
    const m = CONFLICT_STYLE_META[style.key];
    fights.push(`${m.label}: ${m.short}. ${m.body3}`);
  }
  const trigger = p.summary.triggerTop[0];
  if (trigger) fights.push(`Primary trigger: ${TRIGGER_META[trigger.key].phrase}.`);

  fights.push(
    p.axes.conflictEngage > 30
      ? 'Needs resolution quickly. Will not sleep on it comfortably.'
      : p.axes.conflictEngage < -30
        ? 'Needs space first. Pursuing them during this window produces compliance, not resolution, and they will resent it later.'
        : 'Neither pursues nor withdraws strongly. Comparatively easy to fight with.'
  );
  if (p.axes.conflictHeat > 30) fights.push('Expressive under pressure. Volume is not necessarily severity for this client.');
  if (p.axes.harmony > 35) fights.push('Will absorb a great deal to keep the surface calm. What they do not say accumulates.');

  const seq = p.summary.repairTop.map((r) => REPAIR_META[r.key].label);
  if (seq.length) {
    repairs.push(`Repair sequence that actually works: ${seq.join(' → ')}.`);
    repairs.push(`Specifically: ${p.summary.repairTop.map((r) => REPAIR_META[r.key].phrase).join(', then ')}.`);
  }
  const top = p.summary.repairTop[0];
  if (top?.key === 'accountability') repairs.push('A non-specific apology will not close it. The thing must be named.');
  if (top?.key === 'action') repairs.push('Words alone will not close it. They are waiting for evidence the following week.');
  if (top?.key === 'space') repairs.push('Do not resolve immediately. Give the window first.');

  return { fights, repairs };
}

function compromiseNotes(p) {
  const wont = [];
  const flexible = [];

  if (p.axes.physical > 45) wont.push('Physical chemistry. This is structural for them, and no amount of other alignment will substitute.');
  if (p.axes.admiration > 45) wont.push('Being respected by a partner they also respect.');
  if (p.axes.closeness < -45) wont.push('Retaining an independent life inside the relationship.');
  if (p.axes.closeness > 45) wont.push('Genuinely shared daily life. A parallel relationship will not satisfy them.');
  if (p.axes.family > 45) wont.push('Family remaining central.');
  if (p.axes.security > 45) wont.push('Consistency of effort.');
  if (p.axes.rigidity > 45) wont.push('Their stated requirements, which they hold firmly and which are likely to be genuine.');
  if (!wont.length) wont.push('No single axis reached the level where it reads as non-negotiable. This client has more range than most.');

  if (p.axes.rigidity < -30) {
    flexible.push('Their stated requirements are considerably more permeable than they will claim. Across the assessment they indicated that a stated requirement stops mattering quickly once a real person is in front of them. Introduce the near-miss.');
  }
  for (const f of p.flags) {
    if (f.question === 'q18' && f.note.includes('permeable')) {
      flexible.push('Explicitly confirmed: stated requirements are permeable in practice.');
    }
    if (f.note.includes('contradiction')) {
      flexible.push('They chose to hold a requirement and keep seeing the person anyway, leaving it unresolved. Find out which requirement this was - it is usually the most revealing thing in the file.');
    }
  }
  if (!flexible.length) flexible.push('No clear flexibility signal. Treat stated dealbreakers as real until tested.');

  return { wont, flexible };
}

function whoToConsider(p) {
  const consider = [];
  const careful = [];
  const arc = ARCHETYPES[p.archetype.primary];
  const hidden = ARCHETYPES[p.archetype.hidden];

  // bestBrought already begins with "a partner...", so do not prefix an
  // article - that produced "Someone who is a partner who is...".
  const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
  consider.push(`${cap(arc.bestBrought)}.`);
  consider.push(`Also, and less obviously: ${hidden.bestBrought}.`);
  if (p.axes.reassurance > 35) consider.push('Someone naturally expressive who offers reassurance without needing to be asked.');
  if (p.axes.conflictEngage < -30) consider.push('Someone who does not pursue during conflict, or who can learn not to quickly.');
  if (p.axes.conflictEngage > 30) consider.push('Someone who will stay in the room rather than withdraw.');
  if (p.axes.directness < -25) consider.push('Someone attuned enough to read what is not said.');
  if (p.axes.directness > 25) consider.push('Someone who says things plainly. Subtlety will be missed or resented.');

  if (p.axes.pursuit > 35) careful.push('Anyone passive early on. This client will read a lack of pursuit as a lack of interest and disengage before chemistry has a chance.');
  if (p.axes.novelty < -35) careful.push('High-novelty partners. They will be experienced as unstable rather than exciting.');
  if (p.axes.novelty > 35) careful.push('Very steady partners, at least as a first introduction. They will be read as flat.');
  if (p.axes.physical > 45) careful.push('Anyone where the physical dimension is uncertain, regardless of how well everything else reads on paper.');
  if (p.shadow.key === 'veil') careful.push('Partners who are emotionally unreadable. This client will build an interpretation and act on it without checking.');
  if (p.shadow.key === 'fortress') careful.push('Partners who need a lot of visible reassurance early. This client withdraws access under pressure rather than explaining.');
  if (p.shadow.key === 'ledger') careful.push('Partners who take generosity at face value. The account runs silently and is presented all at once.');
  if (p.shadow.key === 'horizon') careful.push('Partners who move fast toward containment. This client keeps an exit warm when they feel confined.');
  if (!careful.length) careful.push('No specific contraindications flagged.');

  return { consider, careful };
}

function questionsToAsk(p) {
  const qs = [];

  if (p.stated.divergent) {
    qs.push('"Tell me about the last person you were genuinely drawn to. What was it about them?" - Listen for whether the answer matches their stated type or their demonstrated one.');
  }
  if (p.summary.giveReceiveSplit) {
    const g = p.summary.giveTop[0], r = p.summary.receiveTop[0];
    qs.push(`"When you have felt most loved by someone, what were they actually doing?" - Their answers indicate they give as ${LOVE_CHANNEL_LABEL[g.key].toLowerCase()} and receive as ${LOVE_CHANNEL_LABEL[r.key].toLowerCase()}. See whether they are aware of the gap.`);
  }
  for (const f of p.flags) {
    if (f.note.includes('ask in person')) {
      qs.push('"Is there a requirement you have kept even though you are not sure it still matters?" - They indicated they hold a requirement and continue anyway, unresolved.');
    }
    if (f.note.includes('blended')) {
      qs.push('"How would you feel being second in someone’s life while their children are young?" - They flagged difficulty with permanent second position.');
    }
    if (f.note.includes('presence outranks prestige')) {
      qs.push('"Would you rather be with someone impressive or someone available?" - They already answered this one way. Confirm it holds.');
    }
  }
  if (p.axes.rigidity > 40) {
    qs.push('"Which of your requirements would you actually break for the right person?" - They hold requirements firmly. Find the one that moves.');
  }
  if (p.shadow.confidence !== 'inferred') {
    qs.push(`"After a relationship disappoints you, what changes about how you date?" - Their answers point toward ${SHADOWS[p.shadow.key].name}. Confirm in their own words.`);
  }
  if (p.axes.reassurance > 40) {
    qs.push('"How long can you go without hearing from someone you are seeing before it bothers you?" - Establish the real tolerance so you can brief the match.');
  }
  if (!qs.length) {
    qs.push('No specific gaps flagged. Use the standard intake conversation.');
  }

  return qs;
}

