/**
 * report-matchmaker.js
 * The private document. The client never sees this.
 *
 * This is where inference is allowed to be explicit - but it is still bound
 * by evidence. Every claim is phrased as an observation about responses
 * ("across several scenarios you consistently preferred...") rather than as
 * a statement about the person's psychology. Nothing here is a diagnosis.
 */

import { ARCHETYPES, SHADOWS } from './archetypes.js';
