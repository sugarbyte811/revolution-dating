function statedType(p) {
  if (!p.stated.top) {
    return {
      label: 'Not clearly declared',
      body: 'This client did not concentrate around a single self-description. Ask directly what they would say they are looking for, and note the answer - it is a data point the assessment did not capture.'
    };
  }
  const arc = ARCHETYPES[p.stated.top];
  return {
    label: arc.name,
    body: `Asked how they would want to be described, they chose language consistent with ${arc.name}. This is the version of themselves they consciously present, and it is likely to be close to the brief they would give you in person.`
  };
}

function attractionType(p) {
  const onset = p.summary.onsetTop[0];
  const parts = [];

  if (onset) {
    parts.push(
      say(3, `immediate attraction for this client is generated by ${ONSET_META[onset.key].phrase}.`)
    );
  }
  if (p.axes.physical > 40) {
    parts.push('Physical charge registers early and is treated as information rather than as a bonus.');
  }
  if (p.axes.intensity > 40) {
    parts.push('They are drawn to high-amplitude people and are likely to find even-keeled partners pleasant but inert.');
  }
  if (p.axes.status > 40) {
    parts.push('Standing and demonstrated ambition contribute meaningfully to initial interest.');
  }
  if (p.axes.novelty > 40) {
    parts.push('Novelty is a live component of attraction, not merely of maintenance.');
  }

  return {
    label: onset ? ONSET_META[onset.key].label : 'Mixed',
    body: parts.join(' ')
  };
}

function relationshipType(p) {
  const arc = ARCHETYPES[p.archetype.primary];
  const hidden = ARCHETYPES[p.archetype.hidden];
  const parts = [];

  parts.push(
    `Their answers suggest they function best long-term with ${arc.bestBrought}.`
  );
  parts.push(
    `Because ${hidden.name} runs underneath the presentation, they will also need ${hidden.bestBrought}, and they are unlikely to ask for this directly.`
  );

  if (isPronounced(p, 'security')) {
    parts.push('Consistency outranks excitement in the long run for this client, regardless of what attracts them initially.');
  }
  if (isPronounced(p, 'reassurance')) {
    parts.push('They require a partner comfortable giving explicit reassurance without experiencing it as a burden.');
  }
  if (p.axes.closeness < -40) {
    parts.push('They need a partner with a genuinely full independent life. A highly available partner will be experienced as pressure within a few months.');
  }

  return { label: arc.name, body: parts.join(' ') };
}

function growthType(p) {
  const arc = ARCHETYPES[p.archetype.primary];
  const parts = [];

  if (p.stated.divergent) {
    const stated = ARCHETYPES[p.stated.top];
    parts.push(
      `Their stated type reads as ${stated.name}, while their behavioural choices point toward ${arc.name}. The growth introduction here is someone closer to the second than the first - they are likely to object on paper and respond in person.`
    );
  }

  if (p.axes.novelty > 35 && p.axes.security < 10) {
    parts.push('Consider someone steadier than their usual pattern. Their answers indicate they are sustained by novelty, and also that novelty has not been producing durable relationships.');
  }
  if (p.axes.intensity > 40) {
    parts.push('Consider someone regulated rather than volatile. They read calm as flat, which is worth testing gently against one well-chosen introduction.');
  }
  if (p.axes.reassurance > 40 && p.axes.pursuit > 30) {
    parts.push('Consider someone openly expressive rather than someone who must be drawn out. Their pattern suggests a history of pursuing people who are difficult to read.');
  }
  if (!parts.length) {
    parts.push('No strong divergence between stated and demonstrated preferences. A growth introduction is less indicated here than a well-matched one.');
  }

  return { label: 'Outside the usual pattern', body: parts.join(' ') };
}

