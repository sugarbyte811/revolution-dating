export function matchmakerReport(p) {
  const chem = chemistryNotes(p);
  const pd = pursuitAndDistance(p);
  const fr = fightAndRepair(p);
  const comp = compromiseNotes(p);
  const who = whoToConsider(p);

  return {
    confidential: true,
    name: p.intake?.preferredName || 'Client',
    completeness: p.complete
      ? 'Complete'
      : `Incomplete - missing ${p.unanswered.length} of 20 responses (${p.unanswered.join(', ')}). Read with caution.`,

    types: {
      stated: statedType(p),
      attraction: attractionType(p),
      relationship: relationshipType(p),
      growth: growthType(p)
    },

    archetype: {
      primary: ARCHETYPES[p.archetype.primary].name,
      hidden: ARCHETYPES[p.archetype.hidden].name,
      shadow: SHADOWS[p.shadow.key].name,
      confidence: p.archetype.confidence,
      shadowConfidence: p.shadow.confidence,
      note:
        p.archetype.confidence === 'tentative'
          ? 'Archetype evidence is thin for this client. Treat the label as provisional and rely on the dimensional sections below.'
          : null
    },

    whatTheyArentSaying: whatTheyArentSaying(p),
    statedVsDemonstrated: statedVsDemonstrated(p),
    createsChemistry: chem.creates,
    sustainsChemistry: chem.sustains,
    killsAttraction: chem.kills,
    howToPursue: pd.pursuit,
    responseToDistance: pd.distance,
    howTheyFight: fr.fights,
    howTheyRepair: fr.repairs,
    wontCompromise: comp.wont,
    flexibleDealbreakers: comp.flexible,
    consider: who.consider,
    approachCarefully: who.careful,
    questionsToAsk: questionsToAsk(p),

    rawFlags: p.flags,
    footer:
      'Confidential. Revolution Dating internal use only. This document contains inferences drawn from assessment responses. It is not a psychological evaluation and must not be characterised as one, to the client or to anyone else.'
  };
}
